"""Context packs: what a coding agent must know about this repository and environment, generated, never hand-written.

`pipewright context build --env <env>` writes APP_CONTEXT.md (the environment's names, rules and policies, the use
cases, the feature sources, the playbooks) and a marked block in the pointer files agents look for (AGENTS.md,
CLAUDE.md, GEMINI.md); text outside the block is the team's and is never touched. The pack is stamped with a
fingerprint of everything it was built from, so `pipewright context check` fails (in CI) when the manifest, a use
case or Pipewright changed since, instead of letting an agent work from a stale picture.

The tools stay the live truth: the pack tells an agent where things are and what the rules are; the MCP tools
(`pipewright mcp`) check against the environment as it is now.
"""

from __future__ import annotations

import hashlib
import json
import re
from pathlib import Path

from pipewright import __version__

PACK = "APP_CONTEXT.md"
POINTERS = ("AGENTS.md", "CLAUDE.md", "GEMINI.md")
BEGIN, END = "<!-- pipewright:begin (generated by `pipewright context build`; edit outside this block) -->", \
    "<!-- pipewright:end -->"
STAMP = re.compile(r"<!-- pipewright-context-stamp: ([0-9a-f]{16}) -->")


def _fingerprint(root: Path, env, usecase_files: list[Path]) -> str:
    h = hashlib.sha256()
    h.update(__version__.encode())
    h.update(json.dumps({"env": env.name, "project": env.project, "region": env.region, "policies": env.policies,
                         "tenants": env.tenants, "features": env.features, "ai": getattr(env, "ai", {}),
                         "orchestrator": env.orchestrator}, sort_keys=True, default=str).encode())
    # The same on every machine: paths in POSIX form and ordered as text (Windows compares paths without case), and
    # line endings normalised (a Windows checkout has CRLF, a CI runner LF; found in the demo's CI).
    for rel, f in sorted((f.relative_to(root).as_posix(), f) for f in usecase_files):
        h.update(rel.encode())
        h.update(f.read_bytes().replace(b"\r\n", b"\n"))
    return h.hexdigest()[:16]


def _usecase_files(root: Path) -> list[Path]:
    base = root / "usecases"
    if not base.is_dir():
        return []
    return [p for p in base.rglob("*") if p.is_file() and p.suffix in (".yaml", ".sql")]


def _features_line(uc) -> str:
    spec = (uc.ml.get("data") or {}).get("features_from")
    if not spec:
        return "from its own prepared table (fine to start; feature tables or groups are recommended)"
    parts = []
    for s in spec.get("sources") or []:
        name = s.get("feature_group") or s.get("table")
        parts.append(f"{name} [{', '.join(s.get('features') or [])}]")
    return "from " + "; ".join(parts)


def _how_to_connect(env) -> list[str]:
    from pipewright.ai import identity

    local = (getattr(env, "ai", None) or {}).get("local_tools") != "forbidden"
    if not identity.hosted(env):
        return ["- Use the Pipewright MCP tools (`pipewright mcp`) to inspect and verify: they are the live truth. "
                "Never guess names, project IDs or policies."]
    return ["- Use the Pipewright MCP tools to inspect: the team's hosted tool server (`pipewright mcp --env "
            f"{env.name} --tenant <team> --print-config` shows how to connect)"
            + ("" if not local else ", or the local `pipewright mcp`") + ". They are the live truth. Never guess "
            "names, project IDs or policies.",
            "- The hosted server has no copy of this repository: its `bootstrap_usecase` returns a skeleton command "
            "and the drafted files to write over it; run `pipewright validate --env "
            f"{env.name}` and `pipewright review --env {env.name}` on the command line, from the repository root. "
            "Never run commands that print table data."]


def render(root: Path, env, playbooks: list[str]) -> tuple[str, str]:
    """(APP_CONTEXT.md text, fingerprint)."""
    from pipewright.ai import identity
    from pipewright.config import resolve_usecase
    from pipewright.config.document import discover_usecases
    from pipewright.errors import ConfigError

    files = _usecase_files(root)
    stamp = _fingerprint(root, env, files)
    L = [f"# Pipewright context: {env.name}", "",
         f"<!-- pipewright-context-stamp: {stamp} -->",
         f"Generated by `pipewright context build --env {env.name}` with Pipewright {__version__}. Do not edit: "
         "rebuild it. `pipewright context check` fails when it is stale.", "",
         "## How to work here", "", *_how_to_connect(env),
         "- Write configuration as YAML under `usecases/<name>/`. Refer to platform resources by name "
         "(`${resources.bigquery_dataset}`, `${buckets.landing}`), never by value.",
         ("- Before proposing a change, run `validate`, `doctor` and `plan` through the tools, fix what fails, then "
          if not identity.hosted(env) else
          f"- Before proposing a change, run `pipewright validate --env {env.name}` and `pipewright doctor --env "
          f"{env.name} --usecase <name>` on the command line, fix what fails, then ")
         + "open a pull request with `pipewright review` as its description. A person approves; never merge, release, "
         "approve or deploy yourself.",
         "- Rows of data are never sent to you. Do not ask for them, and do not paste data into the conversation.", "",
         "## The rules this environment holds every use case to", ""]
    pol = env.policies or {}
    for key in ("promote_model", "deploy_model"):
        if pol.get(key):
            L.append(f"- approvals.{key}: at least `{pol[key]}`.")
    mins = (pol.get("evaluation") or {}).get("min_gates") or {}
    for metric, rule in mins.items():
        L.append(f"- A gate on `{metric}`: {rule if isinstance(rule, dict) else {'min': rule}} at least.")
    if (env.features or {}).get("required"):
        L.append("- Every model feature must come from `data.features_from` (features.required).")
    L += ["- Rows ordered in time use `data.split: { strategy: time, time_column: <cut-off> }`.",
          "- Personal data (`data_protection.personal_data_columns`) is never a feature.",
          "- Dates are not features; derive durations in a feature table.",
          "- Features come from **feature tables or Feature Store feature groups** in the team's granted datasets "
          "(`data.features_from`); a use case's own table holds the entity rows and the label. A prepared table is "
          "allowed to start with, but is not the pattern. If a feature does not exist, say so in the review: the data "
          "team adds it.", "",
          "## Teams (tenants)", ""]
    for t, spec in sorted((env.tenants or {}).items()):
        feats = ((spec.get("features") or {}).get("datasets")) or []
        L.append(f"- **{t}**: dataset `{spec.get('bigquery_dataset', '?')}`, landing prefix "
                 f"`{spec.get('landing_prefix', '-')}`"
                 + (f", feature datasets {', '.join(f'`{d}`' for d in feats)}" if feats else "")
                 + (f", online store `{(spec.get('features') or {}).get('online_store')}`"
                    if (spec.get("features") or {}).get("online_store") else "")
                 + (f"; agent identity `{spec['agent_service_account']}`" if spec.get("agent_service_account") else ""))
    L += ["", "## Use cases", ""]
    for name, path in sorted(discover_usecases(root).items()):
        try:
            uc = resolve_usecase(path, env)
        except ConfigError as e:
            L.append(f"- **{name}**: does not resolve in {env.name} ({str(e).splitlines()[0][:120]})")
            continue
        model = uc.model or {}
        L.append(f"- **{name}** (tenant {uc.tenant}, owner {uc.owner}): pipelines {', '.join(uc.pipelines)}; "
                 f"model `{model.get('name', '-')}`; features {_features_line(uc)}; "
                 f"promote_model {uc.approvals.get('promote_model', '-')}, deploy_model "
                 f"{uc.approvals.get('deploy_model', '-')}.")
    if playbooks:
        L += ["", "## Playbooks", "", "Step-by-step recipes with checks and a definition of done, in "
              "`.pipewright/playbooks/`:", ""]
        L += [f"- `{p}`" for p in playbooks]
    return "\n".join(L) + "\n", stamp


def pointer_block(env_name: str) -> str:
    return (f"{BEGIN}\n## Pipewright\n\nThis repository is a Pipewright MLOps repository. Before changing anything, "
            f"read `{PACK}` (environment `{env_name}`): its names, rules and playbooks. Inspect and verify with the "
            "Pipewright MCP tools (`pipewright mcp`); propose changes as a pull request with `pipewright review`; "
            f"never merge, release, approve or deploy.\n{END}")


def _with_block(existing: str, block: str) -> str:
    if BEGIN in existing and END in existing:
        before = existing.split(BEGIN, 1)[0]
        after = existing.split(END, 1)[1]
        return before + block + after
    sep = "" if not existing else ("\n" if existing.endswith("\n") else "\n\n")
    return existing + sep + block + "\n"


def install_playbooks(root: Path) -> list[str]:
    """Copies Pipewright's playbooks to .pipewright/playbooks/ (replaced on every build: they are Pipewright's)."""
    src = Path(__file__).with_name("playbooks")
    dst = root / ".pipewright" / "playbooks"
    dst.mkdir(parents=True, exist_ok=True)
    names = []
    for f in sorted(src.glob("*.md")):
        (dst / f.name).write_text(f.read_text(encoding="utf-8"), encoding="utf-8")
        names.append(f".pipewright/playbooks/{f.name}")
    return names


def build(root: Path, env, playbooks: list[str] | None = None) -> list[Path]:
    if playbooks is None:
        playbooks = install_playbooks(root)
    text, _ = render(root, env, playbooks)
    written = [root / PACK]
    (root / PACK).write_text(text, encoding="utf-8")
    for name in POINTERS:
        p = root / name
        old = p.read_text(encoding="utf-8") if p.exists() else ""
        new = _with_block(old, pointer_block(env.name))
        if new != old:
            p.write_text(new, encoding="utf-8")
            written.append(p)
    return written


def check(root: Path, env) -> tuple[bool, str]:
    p = root / PACK
    if not p.exists():
        return False, f"{PACK} is missing: run `pipewright context build --env {env.name}`"
    m = STAMP.search(p.read_text(encoding="utf-8"))
    current = _fingerprint(root, env, _usecase_files(root))
    if not m:
        return False, f"{PACK} has no stamp: rebuild it"
    if m.group(1) != current:
        return False, (f"{PACK} is stale (built from {m.group(1)}, now {current}): the manifest, a use case or "
                       f"Pipewright changed; run `pipewright context build --env {env.name}`")
    missing = [n for n in POINTERS if not (root / n).exists() or BEGIN not in (root / n).read_text(encoding="utf-8")]
    if missing:
        return False, f"pointer files without the Pipewright block: {', '.join(missing)}; rebuild the pack"
    return True, f"{PACK} is current ({current})"
