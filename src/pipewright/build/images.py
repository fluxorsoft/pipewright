"""Builds and pushes a use case's component image with Docker."""

from __future__ import annotations

import ast
import configparser
import hashlib
import io
import json
import os
import shutil
import subprocess
import tempfile
from importlib import resources
from pathlib import Path
from urllib.parse import quote

from pipewright.config import ResolvedUseCase
from pipewright.errors import ConfigError


def find_components(components_dir: Path) -> dict[str, str]:
    """function name -> file name, for every @dsl.component / @component function in the directory."""
    found: dict[str, str] = {}
    for path in sorted(Path(components_dir).glob("*.py")):
        try:
            tree = ast.parse(path.read_text(encoding="utf-8"), filename=str(path))
        except SyntaxError as e:
            raise ConfigError(f"{path.name} does not parse: {e}") from e
        for node in tree.body:
            if not isinstance(node, ast.FunctionDef):
                continue
            for deco in node.decorator_list:
                target = deco.func if isinstance(deco, ast.Call) else deco
                name = target.attr if isinstance(target, ast.Attribute) else getattr(target, "id", None)
                if name == "component":
                    if node.name in found:
                        raise ConfigError(f"component {node.name!r} is defined in {found[node.name]} and {path.name}")
                    found[node.name] = path.name
    if not found:
        raise ConfigError(f"no @dsl.component functions found in {components_dir}")
    return found


def kfp_config_ini(components: dict[str, str]) -> str:
    cp = configparser.ConfigParser()
    cp.optionxform = str
    cp["Components"] = dict(sorted(components.items()))
    buf = io.StringIO()
    buf.write("; Generated by Pipewright: maps component functions to files for the KFP executor.\n")
    cp.write(buf)
    return buf.getvalue()


def build_context(uc: ResolvedUseCase, dest: Path) -> Path:
    requirements = uc.requirements or (uc.components_dir / "requirements.txt")
    if not requirements.is_file():
        raise ConfigError(f"no requirements file for the component image (looked for {requirements})")
    from pipewright.checks import kfp_version, ray_version

    pin = kfp_version.check(uc)
    if not pin.ok:
        raise ConfigError(f"kfp version: {pin.message}")
    ray_pin = ray_version.check(uc)
    if not ray_pin.ok:
        raise ConfigError(f"ray version: {ray_pin.message}")
    shutil.copytree(uc.components_dir, dest / "components",
                    ignore=shutil.ignore_patterns("__pycache__", "*.pyc", "kfp_config.ini", "requirements*.txt"))
    shutil.copy(requirements, dest / "requirements.txt")
    if uc.framework == "bqml":                     # Pipewright's own steps: kfp at the compiler's version
        from pipewright.checks.kfp_version import compiler_version

        if not compiler_version():
            raise ConfigError("building the BigQuery ML steps image needs kfp installed (the GCP extra)")
        with open(dest / "requirements.txt", "a", encoding="utf-8") as f:
            f.write(f"kfp=={compiler_version()}\n")
        # Gate 1 in the evaluate step is the same check `pipewright model approve` makes.
        gates = resources.files("pipewright.models").joinpath("gates.py").read_text(encoding="utf-8")
        (dest / "components" / "pipewright_gates.py").write_text(gates, encoding="utf-8")
    # Platform runtime helpers (write_table, log, emit_event): importable by every component.
    templates = resources.files("pipewright.build.templates")
    runtime = templates.joinpath("pipewright_runtime.py").read_text(encoding="utf-8")
    (dest / "components" / "pipewright_runtime.py").write_text(runtime, encoding="utf-8")
    (dest / "kfp_config.ini").write_text(kfp_config_ini(find_components(uc.components_dir)), encoding="utf-8")
    dockerfile = templates.joinpath("components.Dockerfile").read_text(encoding="utf-8")
    (dest / "Dockerfile").write_text(dockerfile, encoding="utf-8")
    return dest


def _docker(*args: str, input_text: str | None = None, quiet: bool = True) -> str:
    exe = shutil.which("docker") or "docker"
    r = subprocess.run([exe, *args], input=input_text, capture_output=quiet, text=True, encoding="utf-8",
                       errors="replace")
    if r.returncode != 0:
        detail = (r.stderr or r.stdout or "").strip()[-2000:] if quiet else ""
        raise ConfigError(f"docker {args[0]} failed{': ' + detail if detail else ''}")
    return (r.stdout or "").strip() if quiet else ""


def docker_login(registry_host: str, token: str) -> None:
    _docker("login", "-u", "oauth2accesstoken", "--password-stdin", f"https://{registry_host}", input_text=token)


def context_hash(ctx: Path, *extra: str) -> str:
    """Content hash of a build context (paths and bytes) and build arguments: equal hashes, equal images."""
    h = hashlib.sha256()
    for path in sorted(p for p in ctx.rglob("*") if p.is_file()):
        h.update(path.relative_to(ctx).as_posix().encode() + b"\0" + path.read_bytes() + b"\0")
    for value in extra:
        h.update(value.encode() + b"\0")
    return h.hexdigest()


def existing_digest(gcp, repository: str, package: str, tag: str) -> str | None:
    """sha256:... of an already pushed tag in an Artifact Registry docker repository, or None."""
    host, project, repo = repository.split("/", 2)
    location = host.removesuffix("-docker.pkg.dev")
    resp = gcp.get(f"https://artifactregistry.googleapis.com/v1/projects/{project}/locations/{location}/"
                   f"repositories/{repo}/packages/{quote(package, safe='')}/tags/{quote(tag, safe='')}")
    if not resp.ok:
        return None
    version = (resp.body or {}).get("version", "")
    return version.rsplit("/", 1)[-1] if "/versions/sha256:" in version else None


def ray_build_context(uc: ResolvedUseCase, dest: Path) -> Path:
    """The Ray image's context: the component modules (Ray jobs import them) and components.ray_requirements."""
    shutil.copytree(uc.components_dir, dest / "components",
                    ignore=shutil.ignore_patterns("__pycache__", "*.pyc", "kfp_config.ini", "requirements*.txt"))
    templates = resources.files("pipewright.build.templates")
    runtime = templates.joinpath("pipewright_runtime.py").read_text(encoding="utf-8")
    (dest / "components" / "pipewright_runtime.py").write_text(runtime, encoding="utf-8")
    extra = uc.ray_requirements.read_text(encoding="utf-8") if uc.ray_requirements else ""
    (dest / "requirements.txt").write_text(extra, encoding="utf-8")
    (dest / "Dockerfile").write_text(templates.joinpath("ray.Dockerfile").read_text(encoding="utf-8"),
                                     encoding="utf-8")
    return dest


def _build_and_push(ctx: Path, repository: str, package: str, uc: ResolvedUseCase, release_id: str,
                    base_image: str | None, verbose: bool, gcp, log, what: str,
                    images_policy: dict | None = None) -> str:
    ref = f"{repository}/{package}"
    if images_policy:                  # policies.images (FR-54): pip installs from the first approved index
        from pipewright.build import allowlist

        reqs = ctx / "requirements.txt"
        if reqs.is_file():
            reqs.write_text(allowlist.with_index(reqs.read_text(encoding="utf-8"), images_policy), encoding="utf-8")
    tag_name = f"{release_id}-{context_hash(ctx, release_id, uc.name, base_image or '')[:12]}"
    tag = f"{ref}:{tag_name}"
    if gcp is not None:
        digest = existing_digest(gcp, repository, package, tag_name)
        if digest:
            log(f"{what} {tag_name} already pushed: reusing it")
            return f"{ref}@{digest}"
    args = ["build", "-t", tag, "--build-arg", f"RELEASE_ID={release_id}", "--build-arg", f"USECASE={uc.name}"]
    if base_image:
        args += ["--build-arg", f"BASE_IMAGE={base_image}"]
    ca_bundle = os.environ.get("PIPEWRIGHT_BUILD_CA_BUNDLE")
    if ca_bundle:
        if not Path(ca_bundle).is_file():
            raise ConfigError(f"PIPEWRIGHT_BUILD_CA_BUNDLE is set but {ca_bundle} is not a file")
        args += ["--secret", f"id=pip_ca,src={ca_bundle}"]
    _docker(*args, str(ctx), quiet=not verbose)
    _docker("push", tag, quiet=not verbose)
    digests = _docker("inspect", "--format", "{{range .RepoDigests}}{{println .}}{{end}}", tag).split()
    for d in digests:
        if d.startswith(ref + "@sha256:"):
            return d
    raise ConfigError(f"pushed {tag} but found no digest for {ref} (got {digests})")


def base_digest(image: str) -> str:
    """image@sha256:... of a base image, from its registry (no pull): what the release contract records."""
    if "@sha256:" in image:
        return image
    out = _docker("buildx", "imagetools", "inspect", image, "--format", "{{json .Manifest}}")
    try:
        digest = json.loads(out).get("digest")
    except ValueError:
        digest = None
    if not digest:
        raise ConfigError(f"could not read the digest of the base image {image}")
    return f"{image.split('@')[0]}@{digest}"


def build_and_push(uc: ResolvedUseCase, repository: str, release_id: str, token: str,
                   base_image: str | None = None, verbose: bool = False, gcp=None, log=print,
                   images_policy: dict | None = None) -> str:
    """Returns the pushed image as repository/name@sha256:digest.

    The tag is <release_id>-<context hash>, never moved (repositories with immutable tags work; contracts pin the
    digest anyway). Re-releasing the same commit with the same Pipewright and dependencies reuses the pushed
    image; a changed context (e.g. a Pipewright upgrade) gets its own tag."""
    docker_login(repository.split("/", 1)[0], token)
    with tempfile.TemporaryDirectory(prefix="pipewright-build-") as tmp:
        ctx = build_context(uc, Path(tmp))
        base_image = base_image or getattr(uc, "base_image", None)       # components.base_image (FR-59)
        if images_policy and images_policy.get("default_base_image") and not base_image:
            base_image = images_policy["default_base_image"]
        return _build_and_push(ctx, repository, f"{uc.name}-components", uc, release_id, base_image, verbose, gcp,
                               log, "component image", images_policy)


SYNTHETIC_KINDS = ("engine", "evaluation")


def synthetic_build_context(uc: ResolvedUseCase, dest: Path, kind: str) -> Path:
    """The context of one of the synthetic pipeline's images (kind: engine or evaluation): Pipewright's steps,
    runtime and synthetic package, its pinned requirements with kfp at the compiler's version, and for the engine
    the use case's synthetic.requirements (for example SDV, which the team installs)."""
    from pipewright.checks.kfp_version import compiler_version
    from pipewright.synthetic import PIPELINE_FILE

    if kind not in SYNTHETIC_KINDS:
        raise ValueError(f"unknown synthetic image {kind!r}")
    templates = resources.files("pipewright.build.templates")
    components = dest / "components"
    components.mkdir(parents=True)
    shutil.copy(PIPELINE_FILE.parent / "synthetic_steps.py", components / "synthetic_steps.py")
    shutil.copytree(PIPELINE_FILE.parent / "runtime", components / "pipewright_synthetic",
                    ignore=shutil.ignore_patterns("__pycache__", "*.pyc"))
    runtime = templates.joinpath("pipewright_runtime.py").read_text(encoding="utf-8")
    (components / "pipewright_runtime.py").write_text(runtime, encoding="utf-8")
    kfp = compiler_version()
    if not kfp:
        raise ConfigError("building the synthetic images needs kfp installed (the GCP extra)")
    requirements = templates.joinpath(f"synthetic-{kind}-requirements.txt").read_text(encoding="utf-8")
    requirements += f"\nkfp=={kfp}\n"
    if kind == "engine" and uc.synthetic_requirements:
        requirements += f"\n# {uc.synthetic_requirements.name} (synthetic.requirements)\n"
        requirements += uc.synthetic_requirements.read_text(encoding="utf-8")
    (dest / "requirements.txt").write_text(requirements, encoding="utf-8")
    (dest / "kfp_config.ini").write_text(kfp_config_ini(find_components(components)), encoding="utf-8")
    dockerfile = templates.joinpath(f"synthetic-{kind}.Dockerfile").read_text(encoding="utf-8")
    (dest / "Dockerfile").write_text(dockerfile, encoding="utf-8")
    return dest


def build_and_push_synthetic(uc: ResolvedUseCase, repository: str, release_id: str, token: str,
                             verbose: bool = False, gcp=None, log=print,
                             images_policy: dict | None = None) -> tuple[str, str]:
    """The synthetic pipeline's images (<name>-synthetic, <name>-synthetic-evaluation), as (engine, evaluation)
    references by digest; same tagging as build_and_push, so an unchanged image is reused."""
    docker_login(repository.split("/", 1)[0], token)
    refs = []
    for kind, package in (("engine", f"{uc.name}-synthetic"), ("evaluation", f"{uc.name}-synthetic-evaluation")):
        with tempfile.TemporaryDirectory(prefix=f"pipewright-synthetic-{kind}-") as tmp:
            ctx = synthetic_build_context(uc, Path(tmp), kind)
            refs.append(_build_and_push(ctx, repository, package, uc, release_id,
                                        (images_policy or {}).get("default_base_image"), verbose, gcp, log,
                                        f"synthetic {kind} image", images_policy))
    return refs[0], refs[1]


def build_and_push_ray(uc: ResolvedUseCase, repository: str, release_id: str, token: str, base_image: str,
                       verbose: bool = False, gcp=None, log=print, images_policy: dict | None = None) -> str:
    """The use case's Ray image (<name>-ray), on the platform's Ray base image; same tagging as build_and_push."""
    docker_login(repository.split("/", 1)[0], token)
    with tempfile.TemporaryDirectory(prefix="pipewright-ray-build-") as tmp:
        ctx = ray_build_context(uc, Path(tmp))
        return _build_and_push(ctx, repository, f"{uc.name}-ray", uc, release_id, base_image, verbose, gcp, log,
                               "Ray image", images_policy)
